function readMarkdownCollection(folderName, existingList = []) {
  const dir = path.join(omniRoot, folderName);
  if (!fs.existsSync(dir)) return existingList || [];

  const existingMap = new Map();
  const existingOrder = new Map();
  (existingList || []).forEach((item, idx) => {
    if (item && item.id) {
      existingMap.set(item.id, item);
      existingOrder.set(item.id, idx);
    }
  });

  const files = fs.readdirSync(dir).filter(f => f.endsWith('.md')).sort();
  if (files.length === 0) return existingList || [];

  const items = [];
  for (const file of files) {
    const fullPath = path.join(dir, file);
    const content = fs.readFileSync(fullPath, 'utf8');
    const parsed = matter(content);
    const data = parsed.data || {};
    const body = (parsed.content || '').trim();
    const id = data.id || file.replace(/\.md$/, '');
    const existing = existingMap.get(id) || {};

    items.push({
      ...existing,
      ...data,
      id,
      name: data.name || data.title || existing.name || id,
      category: data.category || existing.category || folderName,
      description: data.description || existing.description || '',
      body
    });
  }

  items.sort((a, b) => {
    const idxA = existingOrder.has(a.id) ? existingOrder.get(a.id) : 9999;
    const idxB = existingOrder.has(b.id) ? existingOrder.get(b.id) : 9999;
    if (idxA !== idxB) return idxA - idxB;
    return (a.id || '').localeCompare(b.id || '');
  });

  return items;
}

function writeStandaloneModule(folderName, exportName, fileName, existingList) {
  const items = readMarkdownCollection(folderName, existingList);
  const code = `// Autogenerated from src/data/omnicortex/${folderName}
export const ${exportName} = ${JSON.stringify(items, null, 2)};
`;
  fs.writeFileSync(path.join(staticDataRoot, fileName), code, 'utf8');
  return items.length;
}

