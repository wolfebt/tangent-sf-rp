// Societal domain folders (society_*)
const societyDirs = fs.readdirSync(omniRoot, { withFileTypes: true })
  .filter(d => d.isDirectory() && d.name.startsWith('society_'))
  .map(d => d.name)
  .sort();

const societalEntries = [];
for (const sDir of societyDirs) {
  const existingSubset = (existingSupporting.DEFAULT_SOCIETAL_ENTRIES || []).filter(
    e => e.category === sDir || e.sphere_key === sDir
  );
  const synced = readMarkdownCollection(sDir, existingSubset).map(item => ({
    ...item,
    category: sDir,
    sphere_key: item.sphere_key || sDir
  }));
  societalEntries.push(...synced);
}

