import fs from 'fs';
import path from 'path';
import matter from 'gray-matter';
import { fileURLToPath } from 'url';
import { enrichItemWithModifiers } from '../src/engines/tangentModifierEngine.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const traitsDir = path.join(projectRoot, 'src', 'data', 'omnicortex', 'traits');
const targetFile = path.join(projectRoot, 'src', 'data', 'speciesTraitsData.js');

function syncTraits() {
  if (!fs.existsSync(traitsDir)) {
    console.error(`Traits directory not found at: ${traitsDir}`);
    process.exit(1);
  }

  const files = fs.readdirSync(traitsDir).filter(f => f.endsWith('.md')).sort();
  console.log(`Found ${files.length} trait markdown files in ${traitsDir}`);

  const allTraits = [];
  const speciesTraitsBasic = [];
  const speciesTraitsAdvanced = [];
  const speciesTraitsElite = [];
  const occupationalTraits = [];
  const originTraits = [];
  const archetypeTraits = [];
  const factionTraits = [];

  for (const file of files) {
    const fullPath = path.join(traitsDir, file);
    const content = fs.readFileSync(fullPath, 'utf8');
    const parsed = matter(content);
    const data = parsed.data || {};
    const body = (parsed.content || '').trim();

    const id = data.id || file.replace(/\.md$/, '');
    const name = data.name || data.title || id;
    const rawTraitType = data.trait_type || 'Species Trait';
    const traitType = rawTraitType === 'Signature Trait' ? 'Archetype Trait' : rawTraitType;
    const traitTier = data.trait_tier || 'Basic';
    const classification = data.classification || data.type || 'Physical';
    const cp = typeof data.costs?.cp === 'number' ? data.costs.cp : (typeof data.costs?.bp === 'number' ? data.costs.bp : (typeof data.cp === 'number' ? data.cp : (typeof data.bp === 'number' ? data.bp : 1)));
    const bp = cp;

    let description = '';
    if (body) {
      const descMatch = body.match(/(?:^|\n)## Description[^\n]*\n([\s\S]*?)(?=(?:\n##\s)|$)/i);
      if (descMatch) description = descMatch[1].trim();
    }
    if (!description) {
      description = data.description || '';
    }

    let mechanics = data.mechanic || data.mechanics || '';
    if (body) {
      const mechMatch = body.match(/(?:^|\n)## Mechanics[^\n]*\n([\s\S]*?)(?=(?:\n##\s)|$)/i);
      if (mechMatch && mechMatch[1].trim()) mechanics = mechMatch[1].trim();
    }
    if (!mechanics) {
      mechanics = description;
    }

    let rules = data.rules || data.special_rules || '';
    if (!rules && body) {
      const ruleMatch = body.match(/(?:^|\n)## Special Rules[^\n]*\n([\s\S]*?)(?=(?:\n##\s)|$)/i);
      if (ruleMatch) rules = ruleMatch[1].trim();
    }
    if (!rules) {
      rules = `${traitTier} ${traitType} (${cp} CP).`;
    }

    const rawTraitObj = {
      id,
      name,
      category: 'traits',
      trait_type: traitType,
      trait_tier: traitTier,
      classification,
      type: classification,
      cp,
      bp,
      costs: { cp, bp },
      is_ranked: Boolean(data.is_ranked),
      desc: description,
      description,
      mechanics,
      mechanic: mechanics,
      rules,
      special_rules: rules,
      modifiers: Array.isArray(data.modifiers) ? data.modifiers : [],
      package_traits: Array.isArray(data.package_traits) ? data.package_traits.map(t => ({
        ...t,
        cp: Number(t.cp ?? t.bp ?? 1),
        bp: Number(t.bp ?? t.cp ?? 1)
      })) : [],
      body
    };

    const traitObj = enrichItemWithModifiers(rawTraitObj);
    allTraits.push(traitObj);

    if (traitType === 'Occupational Trait' || traitType === 'Common Occupational Trait') {
      occupationalTraits.push(traitObj);
    } else if (traitType === 'Origin Trait') {
      originTraits.push(traitObj);
    } else if (traitType === 'Archetype Trait') {
      archetypeTraits.push(traitObj);
    } else if (traitType === 'Faction Trait') {
      factionTraits.push(traitObj);
    } else {
      if (traitTier === 'Advanced') speciesTraitsAdvanced.push(traitObj);
      else if (traitTier === 'Elite') speciesTraitsElite.push(traitObj);
      else speciesTraitsBasic.push(traitObj);
    }
  }

  // Sort alphabetically
  allTraits.sort((a, b) => (a.name || '').localeCompare(b.name || ''));

  const outputCode = `/**
 * Auto-generated by Omnicortex Trait Sync Engine
 * Source of Truth: src/data/omnicortex/traits/*.md
 */

export const SPECIES_TRAITS_BASIC = ${JSON.stringify(speciesTraitsBasic, null, 2)};

export const SPECIES_TRAITS_ADVANCED = ${JSON.stringify(speciesTraitsAdvanced, null, 2)};

export const SPECIES_TRAITS_ELITE = ${JSON.stringify(speciesTraitsElite, null, 2)};

export const OCCUPATIONAL_TRAITS = ${JSON.stringify(occupationalTraits, null, 2)};

export const ORIGIN_TRAITS = ${JSON.stringify(originTraits, null, 2)};

export const ARCHETYPE_TRAITS = ${JSON.stringify(archetypeTraits, null, 2)};

export const FACTION_TRAITS = ${JSON.stringify(factionTraits, null, 2)};

// Species Traits branch dataset (under Species in Cortex)
export const ALL_SPECIES_TRAITS = [
  ...SPECIES_TRAITS_BASIC,
  ...SPECIES_TRAITS_ADVANCED,
  ...SPECIES_TRAITS_ELITE
];

// Consolidated Traits tab dataset (Origins, Careers/Occupations, Archetypes, Factions)
export const ALL_PILLAR_TRAITS = [
  ...ORIGIN_TRAITS,
  ...OCCUPATIONAL_TRAITS,
  ...ARCHETYPE_TRAITS,
  ...FACTION_TRAITS
];

// Complete combined traits lookup for Folio and cross-pillar resolution
export const ALL_CANONICAL_TRAITS = [
  ...ALL_SPECIES_TRAITS,
  ...ALL_PILLAR_TRAITS
];

export const DEFAULT_SPECIES_TRAITS = ALL_SPECIES_TRAITS;

export const getTraitById = (id) => ALL_CANONICAL_TRAITS.find(t => t.id === id);

/**
 * Enriches a trait object with all canonical metadata (category, trait_type, trait_tier,
 * classification, type, CP, BP, costs, description, mechanic, rules, note, modifiers)
 * for Codex Matrix editing, Folio sheet rendering, or Omnicortex DBM inspection.
 */
export const getEnrichedTraitData = (trait) => {
  if (!trait) return null;
  const rawId = (trait.id || '').toString().trim();
  const cleanId = rawId.replace(/^trait-(?:sig-)?/i, '').toLowerCase();
  const rawName = (trait.name || trait.title || '').toString().trim().toLowerCase();

  const canonical = ALL_CANONICAL_TRAITS.find(t => {
    const tId = (t.id || '').toString().trim().toLowerCase();
    const tCleanId = tId.replace(/^trait-(?:sig-)?/i, '');
    const tName = (t.name || t.title || '').toString().trim().toLowerCase();
    return (rawId && tId === rawId.toLowerCase()) ||
           (cleanId && tCleanId === cleanId) ||
           (rawName && tName === rawName);
  });

  const name = trait.name || trait.title || canonical?.name || canonical?.title || 'Trait';
  const id = trait.id || canonical?.id || \`trait-\${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}\`;
  const rawTraitType = trait.trait_type || canonical?.trait_type || trait.sourceDetail || 'Species Trait';
  const trait_type = rawTraitType === 'Signature Trait' ? 'Archetype Trait' : rawTraitType;
  const trait_tier = trait.trait_tier || canonical?.trait_tier || 'Basic';
  const classification = trait.classification || canonical?.classification || trait.type || canonical?.type || 'Physical';
  const cp = trait.cp !== undefined ? Number(trait.cp) : (canonical?.cp !== undefined ? Number(canonical.cp) : 1);
  const bp = trait.bp !== undefined ? Number(trait.bp) : (canonical?.bp !== undefined ? Number(canonical.bp) : cp);
  const description = trait.description || trait.desc || canonical?.description || canonical?.desc || '';
  const mechanic = trait.mechanic || trait.mechanics || canonical?.mechanic || canonical?.mechanics || '';
  const note = trait.note || trait.notes || canonical?.note || canonical?.notes || '';
  const rules = trait.rules || trait.special_rules || canonical?.rules || canonical?.special_rules || \`\${trait_tier} \${trait_type} (\${cp} CP).\`;
  const modifiers = Array.isArray(trait.modifiers) && trait.modifiers.length > 0
    ? trait.modifiers
    : (Array.isArray(canonical?.modifiers) ? canonical.modifiers : []);

  return {
    ...(canonical || {}),
    ...trait,
    id,
    name,
    category: 'traits',
    trait_type,
    trait_tier,
    classification,
    type: classification,
    cp,
    bp,
    costs: {
      cp,
      bp,
      ...(canonical?.costs || {}),
      ...(trait.costs || {})
    },
    description,
    desc: description,
    mechanic,
    mechanics: mechanic,
    note,
    notes: note,
    notesList: Array.isArray(trait.notesList) ? trait.notesList : (Array.isArray(canonical?.notesList) ? canonical.notesList : (note ? [note] : [])),
    rules,
    special_rules: rules,
    modifiers,
    modifier_options: trait.modifier_options || canonical?.modifier_options || {
      enabled: false,
      mode: 'single',
      value: 2,
      options: []
    },
    selected_option_id: trait.selected_option_id || canonical?.selected_option_id || '',
    selected_skills: Array.isArray(trait.selected_skills) ? trait.selected_skills : (Array.isArray(canonical?.selected_skills) ? canonical.selected_skills : [])
  };
};
`;

  fs.writeFileSync(targetFile, outputCode, 'utf8');
  console.log(`Successfully synced ${allTraits.length} canonical traits to: ${targetFile}`);
}

syncTraits();
