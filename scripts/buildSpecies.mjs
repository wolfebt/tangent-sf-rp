// ==========================================
// 1. PARSE MASTER LIST & BUILD POINT BREAKDOWN
// ==========================================
const lines = rawContent.split('\n');
const masterMatrix = new Map();

let inMasterTable = false;
let currentLineage = 'Independent';

for (let i = 0; i < lines.length; i++) {
  const line = lines[i].trim();
  if (line.includes('| SPECIES / SUBSPECIES |')) {
    inMasterTable = true;
    continue;
  }
  if (inMasterTable) {
    if (line.startsWith('| :---') || line.startsWith('|:---') || line === '') continue;
    if (!line.startsWith('|')) {
      inMasterTable = false;
      continue;
    }
    const cols = line.split('|').map(c => c.trim()).slice(1, -1);
    if (cols.length >= 6) {
      const rawName = cols[0].replace(/\*\*/g, '').trim();
      const isSub = rawName.startsWith('-') || rawName.startsWith('\\-');
      const cleanName = rawName.replace(/^[\\-]+\s*/, '').trim();

      if (!isSub) {
        currentLineage = cleanName;
      }

      const typeCost = cols[1] || '';
      const attributes = cols[2] || '';
      const skills = cols[3] || '';
      const featuresTraits = cols[4] || '';
      const stigma = cols[5] || '';
      const totalBp = cols[6] || '';

      const key = cleanName.toLowerCase().replace(/[^a-z0-9]/g, '');
      masterMatrix.set(key, {
        rawName,
        name: cleanName,
        isSub,
        lineage: currentLineage,
        typeCost,
        attributes,
        skills,
        featuresTraits,
        stigma,
        totalBp
      });
    }
  }
}

console.log(`Parsed ${masterMatrix.size} entries from Master List table.`);

// ==========================================
// 2. PARSE NARRATIVE SECTIONS IN THE DOCUMENT
// ==========================================
const h1Regex = /^# \*\*([^*]+)\*\*/gm;
const sectionMatches = [];
let match;
while ((match = h1Regex.exec(rawContent)) !== null) {
  sectionMatches.push({
    title: match[1].trim().replace(/\\/g, ''),
    startIndex: match.index,
    length: match[0].length
  });
}

const detailedSections = new Map();
for (let i = 0; i < sectionMatches.length; i++) {
  const current = sectionMatches[i];
  const next = sectionMatches[i + 1];
  const body = rawContent.substring(
    current.startIndex + current.length,
    next ? next.startIndex : rawContent.length
  ).trim();

  // Deduplicate consecutive identical titles
  const cleanTitle = current.title.replace(/\s*\*\s*/g, '').trim();
  const key = cleanTitle.toLowerCase().replace(/[^a-z0-9]/g, '');
  
  if (!detailedSections.has(key) || body.length > (detailedSections.get(key)?.body?.length || 0)) {
    detailedSections.set(key, {
      rawTitle: current.title,
      cleanTitle,
      body
    });
  }
}

console.log(`Extracted ${detailedSections.size} detailed narrative sections.`);

